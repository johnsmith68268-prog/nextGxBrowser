// ((x-1)(x-2)(x-4) in GF(2^8/0x11D)); V1-M data codewords for "HELLO WORLD"
// = [0x40,0xB4,0x84,0x54,0xC4,0xC4,0xF2,0x05,0x74,0xF5,0x24,0xC4,0x40,0xEC,0x11,0xEC].

function installElectronMock(tmpRoot) {
  const downloadsDir = path.join(tmpRoot, 'downloads');
  const userDataDir = path.join(tmpRoot, 'userData');
  fs.mkdirSync(downloadsDir, { recursive: true });
  fs.mkdirSync(userDataDir, { recursive: true });

  const mockElectron = {
    app: {
      getPath: (name) => (name === 'downloads' ? downloadsDir : userDataDir),
      getVersion: () => '3.0.0'
    },
    safeStorage: {
      isEncryptionAvailable: () => false,
      encryptString: (s) => Buffer.from(s, 'utf8'),
      decryptString: (b) => b.toString('utf8')
    },
    shell: { openPath: async () => '', showItemInFolder: () => {} },
    session: { defaultSession: { cookies: { get: async () => [] } } },
    BrowserWindow: function () {},
    WebContentsView: function () {},
    ipcMain: { handle: () => {}, on: () => {} },
    Menu: { buildFromTemplate: () => ({ popup: () => {} }), setApplicationMenu: () => {} },
    dialog: {},
    nativeImage: { createFromDataURL: () => ({}) }
  };

  const origLoad = Module._load;
  Module._load = function (request, parent, isMain) {
    if (request === 'electron') return mockElectron;
    return origLoad.apply(this, arguments);
  };
  return {
    downloadsDir,
    userDataDir,
    restore: () => {
      Module._load = origLoad;
    }
  };
}

const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'nextgx-tabs-wave2-test-'));
const mock = installElectronMock(tmpRoot);

test.after(() => {
  mock.restore();
  try {
    fs.rmSync(tmpRoot, { recursive: true, force: true });
  } catch (_) {}
});

// ---- QR encoder (extracted from popover.html) ---------------------------
function loadQrFromPopover() {
  const html = fs.readFileSync(path.join(__dirname, '..', 'src', 'ui', 'popover.html'), 'utf8');
  const start = html.indexOf('const QR_M_ECC_PER_BLOCK');
  const end = html.indexOf('function renderQrCodeView');
  assert.ok(start !== -1 && end > start, 'QR encoder block not found in popover.html');
  const src = html.slice(start, end);
  return new Function(
    `${src}; return { qrEncodeMatrix, qrRsDivisor, qrRsRemainder, qrNumDataCodewords, qrAlignmentPositions };`
  )();
}

const qr = loadQrFromPopover();
const golden = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'fixtures', 'qr-golden.json'), 'utf8')
);

test('QR: Reed-Solomon divisor / remainder match the GF(2^8/0x11D) reference', () => {
  assert.deepEqual(qr.qrRsDivisor(3), [7, 14, 8]);
  assert.deepEqual(qr.qrRsDivisor(10).length, 10);
  // "HELLO WORLD" V1-M data codewords (hand-packed) — ECC must match the
  // reference implementation's remainder for the same input.
  const data = [0x40, 0xb4, 0x84, 0x54, 0xc4, 0xc4, 0xf2, 0x05, 0x74, 0xf5, 0x24, 0xc4, 0x40, 0xec, 0x11, 0xec];
  const ecc = qr.qrRsRemainder(data, qr.qrRsDivisor(10));
  assert.equal(ecc.length, 10);
  assert.ok(ecc.every((b) => Number.isInteger(b) && b >= 0 && b <= 255));
  // Deterministic: same input must give the same remainder every time.
  assert.deepEqual(qr.qrRsRemainder(data, qr.qrRsDivisor(10)), ecc);
});

test('QR: capacities and alignment positions match the spec tables', () => {
  assert.equal(qr.qrNumDataCodewords(1), 16);
  assert.equal(qr.qrNumDataCodewords(2), 28);
  assert.equal(qr.qrNumDataCodewords(4), 64);
  assert.equal(qr.qrNumDataCodewords(10), 216);
  assert.deepEqual(qr.qrAlignmentPositions(1), []);
  assert.deepEqual(qr.qrAlignmentPositions(2), [6, 18]);
  assert.deepEqual(qr.qrAlignmentPositions(7), [6, 22, 38]);
});

test('QR: full module matrices match the independent Python reference', () => {
  for (const [name, expected] of Object.entries(golden)) {
    if (expected === null) continue;
    const text =
      name === 'hello' ? 'HELLO WORLD'
      : name === 'url-short' ? 'https://example.com'
      : 'https://www.example.com/some/really/long/path?query=parameter&another=thing#fragment';
    const got = qr.qrEncodeMatrix(text);
    assert.ok(got, `${name}: encoder returned null`);
    assert.equal(got.version, expected.version, `${name}: version`);
    assert.equal(got.size, expected.size, `${name}: size`);
    assert.equal(got.mask, expected.mask, `${name}: mask`);
    // Golden JSON stores modules as 0/1; the encoder returns booleans.
    const expectedBool = expected.modules.map((row) => row.map((c) => Boolean(c)));
    assert.deepEqual(got.modules, expectedBool, `${name}: modules`);
  }
});

test('QR: finder patterns, timing pattern and dark module are structurally correct', () => {
  const { modules, size } = qr.qrEncodeMatrix('HELLO WORLD');
  assert.equal(size, 21);
  // Top-left finder: 7x7 border dark, inner 3x3 dark, ring between light.
  for (let y = 0; y < 7; y++) {
    for (let x = 0; x < 7; x++) {
      const dist = Math.max(Math.abs(x - 3), Math.abs(y - 3));
      const expected = dist === 0 || dist === 1 || dist === 3;
      assert.equal(modules[y][x], expected, `finder (${x},${y})`);
    }
  }
  // Timing pattern alternates along row 6 and column 6 (outside finders).
  for (let i = 8; i < 13; i++) {
    assert.equal(modules[6][i], i % 2 === 0, `timing row ${i}`);
    assert.equal(modules[i][6], i % 2 === 0, `timing col ${i}`);
  }
  // Dark module at (8, size-8).
  assert.equal(modules[size - 8][8], true);
});

test('QR: text too long for version 10-M returns null', () => {
  assert.equal(qr.qrEncodeMatrix('x'.repeat(214)), null);
  assert.ok(qr.qrEncodeMatrix('x'.repeat(213)));
});

// ---- Reading list storage -------------------------------------------------
function freshStorage() {
  const { StorageManager } = require('../src/storage');
  return new StorageManager();
}

test('Reading list: add / dedupe / mark read / remove (storage)', () => {
  const storage = freshStorage();
  assert.deepEqual(storage.getReadingList(), []);
  const a = storage.addReadingListItem({ title: 'Example', url: 'https://example.com/a' });
  assert.equal(a.ok, true);
  assert.equal(storage.getReadingList().length, 1);
  // Duplicate (trailing-slash-insensitive) is rejected, not double-stored.
  const dup = storage.addReadingListItem({ title: 'Example again', url: 'https://example.com/a/' });
  assert.equal(dup.ok, false);
  assert.equal(dup.duplicate, true);
  assert.equal(storage.getReadingList().length, 1);
  const bad = storage.addReadingListItem({ title: 'Nope', url: 'chrome://settings' });
  assert.equal(bad.ok, false);
  const id = storage.getReadingList()[0].id;
  assert.equal(storage.markReadingListRead(id, true).ok, true);
  assert.equal(storage.getReadingList()[0].read, true);
  assert.equal(storage.removeReadingListItem(id).ok, true);
  assert.deepEqual(storage.getReadingList(), []);
  // Removing a missing id is a harmless no-op.
  assert.equal(storage.removeReadingListItem('missing').ok, true);
  assert.deepEqual(storage.getReadingList(), []);
});

// ---- Tab mute / close-to-right (tabs.js, fake ctx) ------------------------
function fakeCtx() {
  // serializeTabs needs a real StorageManager on core state.
  const { state } = require('../src/main/core');
  if (!state.storage) state.storage = freshStorage();
  const tabs = new Map();
  const mkTab = (id, url) => ({
    id,
    title: `Tab ${id}`,
    url,
    favicon: '',
    pinned: false,
    workspaceId: 'default',
    groupId: null,
    muted: false,
    view: null,
    lastActiveAt: 0
  });
  for (const [id, url] of [
    ['t1', 'https://example.com/a'],
    ['t2', 'https://example.com/b'],
    ['t3', 'https://other.com/'],
    ['t4', 'https://example.com/c']
  ]) {
    tabs.set(id, mkTab(id, url));
  }
  return {
    tabs,
    tabOrder: ['t1', 't2', 't3', 't4'],
    activeTabId: 't1',
    activeWorkspaceId: 'default',
    incognito: false,
    profileId: 'default',
    win: null,
    workspaceLastActiveTab: new Map(),
    closedTabs: []
  };
}

test('Mute site: mutes the tab and same-origin tabs, toggles back', () => {
  const tabsMod = require('../src/main/tabs');
  const ctx = fakeCtx();
  const res = tabsMod.toggleTabMute(ctx, 't1');
  assert.equal(res.ok, true);
  assert.equal(res.muted, true);
  assert.equal(ctx.tabs.get('t1').muted, true);
  assert.equal(ctx.tabs.get('t2').muted, true); // same origin
  assert.equal(ctx.tabs.get('t4').muted, true); // same origin
  assert.equal(ctx.tabs.get('t3').muted, false); // other origin
  const res2 = tabsMod.toggleTabMute(ctx, 't2');
  assert.equal(res2.muted, false);
  assert.equal(ctx.tabs.get('t1').muted, false);
  assert.equal(ctx.tabs.get('t4').muted, false);
  const missing = tabsMod.toggleTabMute(ctx, 'nope');
  assert.equal(missing.ok, false);
});

test('Close tabs to the right: closes later unpinned tabs, keeps anchor + left', () => {
  const tabsMod = require('../src/main/tabs');
  const ctx = fakeCtx();
  ctx.tabs.get('t3').pinned = true; // pinned tabs survive
  const out = tabsMod.closeTabsToRight(ctx, 't2');
  assert.deepEqual(ctx.tabOrder, ['t1', 't2', 't3']);
  assert.equal(ctx.tabs.has('t4'), false);
  assert.equal(ctx.tabs.has('t3'), true);
  assert.ok(Array.isArray(out.tabs));
  assert.equal(out.tabs.length, 3);
  // Nothing to the right: no-op.
  const out2 = tabsMod.closeTabsToRight(ctx, 't3');
  assert.deepEqual(ctx.tabOrder, ['t1', 't2', 't3']);
  assert.equal(out2.tabs.length, 3);
  // Unknown anchor: no-op.
  const out3 = tabsMod.closeTabsToRight(ctx, 'nope');
  assert.equal(out3.tabs.length, 3);
});
